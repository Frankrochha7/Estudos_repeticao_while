//Faça um algoritmo que imprima a tabuada do 5.

public class Exercicio5 {
    public static void main(String[] args) {
        int multiplicador = 1;
        while (multiplicador <= 10) {
            System.out.println("5 x " + multiplicador + " = " + (5 * multiplicador));
            multiplicador++;
        }
    }
}